#!/usr/bin/env python3
"""Export the runnable sources into the port repository (a separate git repo).

  tools/export_port.py DEST            (e.g. ~/dev/ivona-port)

Writes, under DEST:
  src/<bin>/...      exactly the TUs tools/build_runnable.py compiles for the engine and the
                     voice library (function-table credits plus their "extra" lists), with the
                     headers and .inc files next to them
  include/           the shared headers
  src/libvoice_en_gb_amy/data/assets.c
                     the byte tables tools/gen_assets.py extracts from target/, as C, so the port
                     never reads the original binaries
  exports/<bin>.exports
                     the version scripts that keep each library's original exports
  build.mk           per binary: the source list, and per-file flags that change meaning
                     (defines, include paths of vendored libraries, -fsigned-char); the
                     matching-only flags (-march, -O levels, -finline-limit, ...) are dropped
  EXPORTED_FROM      the decomp commit this came from

The port's own files (Makefile, README, third_party/, its git history) are never touched, so
re-running after the decomp moves on refreshes the sources only. Files the decomp no longer
exports are listed, not deleted.
"""
import os
import re
import shutil
import subprocess
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__)))
from dc.project import Binary, ROOT, path  # noqa: E402
from dc import build  # noqa: E402
import build_runnable  # noqa: E402

BINS = ["libttsivonavoice", "libvoice_en_gb_amy"]
EXPORTED_DIRS = ["src", "include"]
# compile flags that only serve matching the 32-bit ARM original
DROP = re.compile(r"^(-march=.*|-mtune=.*|-msoft-float|-marm|-mthumb|-O.*|-finline-limit=.*|"
                  r"-fomit-frame-pointer|-fstrict-aliasing|-funswitch-loops|-funwind-tables|"
                  r"-ffunction-sections|-fpic|-fno-stack-protector|-no-canonical-prefixes|"
                  r"-I/opt/.*|-Iinclude|-Iinclude/flite|-std=.*|-c|-o|-fno-exceptions|-fno-rtti|"
                  r"-fno-inline|-fno-inline-functions|-fstack-protector)$")
VENDOR_INC = {"build/vendor/": "third_party/"}


def sources(bn: str) -> list[str]:
    t = build_runnable.TARGETS[bn]
    b = Binary(bn)
    srcs = {f.src for f in b.funcs if f.src.startswith("src/")} | set(t["extra"])
    for fn in t.get("lifted", []):
        raise SystemExit(f"{bn}: {fn} is still lifted from the binary; decompile it first")
    return sorted(s for s in srcs if os.path.exists(path(s)))


def flags(bn: str, src: str) -> list[str]:
    cmd = build.compile_cmd(Binary(bn), src)[1:]
    out, skip = [], False
    for x in cmd:
        if skip:
            skip = False
            continue
        if x in ("-o",):
            skip = True
            continue
        if x == src or DROP.match(x):
            continue
        for a, b in VENDOR_INC.items():
            x = x.replace(a, b)
        out.append(x)
    return out


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    dest = os.path.abspath(os.path.expanduser(sys.argv[1]))
    os.makedirs(dest, exist_ok=True)
    wanted = set()
    mk = ["# generated by the decomp's tools/export_port.py; do not edit (re-export instead)", ""]
    for bn in BINS:
        srcs = sources(bn)
        common = None
        per = {}
        for s in srcs:
            per[s] = flags(bn, s)
            common = per[s] if common is None else [x for x in common if x in per[s]]
        var = bn.upper()
        mk.append(f"{var}_SRCS = \\")
        mk += [f"\t{s} \\" for s in srcs]
        mk.append("")
        defines = build_runnable.TARGETS[bn]["defines"]
        mk.append(f"{var}_FLAGS = {' '.join(common + defines)}")
        for s in srcs:
            extra = [x for x in per[s] if x not in common]
            if extra:
                mk.append(f"{var}_{s}_FLAGS = {' '.join(extra)}")
        mk.append("")
        wanted.update(srcs)
        # headers and includes living next to the sources
        for d in sorted({os.path.dirname(s) for s in srcs}):
            for fn in os.listdir(path(d)):
                if fn.endswith((".h", ".inc")):
                    wanted.add(os.path.join(d, fn))
    for root, _, files in os.walk(path("include")):
        for fn in files:
            if fn.endswith((".h", ".inc")):
                wanted.add(os.path.relpath(os.path.join(root, fn), ROOT))
    for rel in sorted(wanted):
        d = os.path.join(dest, rel)
        os.makedirs(os.path.dirname(d), exist_ok=True)
        shutil.copy2(path(rel), d)
    # the exported symbols of each library (gold/ld version scripts)
    for bn in BINS:
        rel = f"config/{bn}.exports"
        os.makedirs(os.path.join(dest, "exports"), exist_ok=True)
        shutil.copy2(path(rel), os.path.join(dest, "exports", f"{bn}.exports"))
    # the byte tables, as committed C in the port
    data = "src/libvoice_en_gb_amy/data/assets.c"
    os.makedirs(os.path.join(dest, os.path.dirname(data)), exist_ok=True)
    subprocess.run([sys.executable, path("tools", "gen_assets.py"), "libvoice_en_gb_amy",
                    os.path.join(dest, data)], check=True)
    wanted.add(data)
    mk[mk.index("LIBVOICE_EN_GB_AMY_SRCS = \\") + 1:1] = [f"\t{data} \\"]
    with open(os.path.join(dest, "build.mk"), "w") as f:
        f.write("\n".join(mk) + "\n")
    commit = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True,
                            cwd=ROOT).stdout.strip()
    dirty = subprocess.run(["git", "status", "--porcelain", "--", *EXPORTED_DIRS, "config"],
                           capture_output=True, text=True, cwd=ROOT).stdout.strip()
    with open(os.path.join(dest, "EXPORTED_FROM"), "w") as f:
        f.write(f"{commit}{' (with uncommitted changes)' if dirty else ''}\n")
    stale = []
    for top in EXPORTED_DIRS:
        for root, _, files in os.walk(os.path.join(dest, top)):
            for fn in files:
                rel = os.path.relpath(os.path.join(root, fn), dest)
                if rel not in wanted:
                    stale.append(rel)
    print(f"exported {len(wanted)} files to {dest} from {commit[:7]}")
    for s in stale:
        print(f"  no longer exported (delete if unused): {s}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
